const assert=require('node:assert/strict');
const {model}=require('../equilibrio.js');
const data={custo:6000,preco:120,produtividade:60};
const m=model(data);
assert.equal(m.equilibrium,50);
assert.equal(m.min,0);
assert.equal(m.max,90);
assert.equal(m.point(30).balance,-2400);
assert.equal(m.point(50).balance,0);
assert.equal(m.point(90).balance,4800);
assert.equal(m.point(60).revenue,7200);
assert.equal(m.point(60).balance,1200);
assert.equal(m.point(50).y,m.y(6000));
assert.ok(m.point(90).x<=432);
assert.equal(m.point(0).revenue,0);
assert.deepEqual(data,{custo:6000,preco:120,produtividade:60});
const screenshot=model({custo:6000,preco:150,produtividade:100});
assert.equal(screenshot.equilibrium,40);
assert.equal(screenshot.point(86.42).balance,6963);
const below=model({custo:6000,preco:120,produtividade:10});
assert.ok(below.max>below.equilibrium);
const exact=model({custo:100,preco:3,produtividade:60.1234});
assert.equal(exact.step,.0001);
assert.equal(exact.point(60.1234).quantity,60.1234);
assert.equal(exact.point(exact.equilibrium).balance,0);
assert.equal(model({custo:0,preco:120,produtividade:60}).equilibrium,0);
console.log('Equilíbrio: cruzamento, perda, saldo, limites, precisão e conta base preservada.');
